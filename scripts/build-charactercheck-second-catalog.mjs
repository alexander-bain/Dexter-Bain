import fs from "node:fs/promises";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const DATA_DIRECTORY = path.join(ROOT, "charactercheck", "data");
const generationArgument = process.argv.find((argument) => argument.startsWith("--generation="));
const GENERATION = Number(generationArgument?.split("=")[1] || 2);
if (!Number.isInteger(GENERATION) || GENERATION < 2) {
  throw new Error("--generation must be an integer of 2 or greater.");
}
const OUTPUT = path.join(DATA_DIRECTORY, `expanded-catalog-${GENERATION}.js`);
const COLLECTION = GENERATION === 2
  ? { id: "encore", label: "500 More Favorites" }
  : { id: `encore-${GENERATION - 1}`, label: GENERATION === 3 ? "Another 500 Favorites" : `Expansion ${GENERATION} Favorites` };
const USER_AGENT = "DexterBainCharacterCheck/1.0 (https://dexterbain.com/charactercheck/)";
const TARGETS = [
  { type: "show", instance: "Q5398426", count: 250 },
  { type: "movie", instance: "Q11424", count: 250 },
];
const ALTERNATE_TITLE_BLOCKLIST = new Set([
  "house m d",
  "harry potter and the philosopher s stone",
  "e t",
  "the mummy",
  "star wars episode iv a new hope",
  "star wars episode v the empire strikes back",
  "star wars episode vi return of the jedi",
]);

function normalizeTitle(value) {
  return String(value || "")
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/&/g, "and")
    .replace(/[^a-zA-Z0-9]+/g, " ")
    .trim()
    .toLowerCase();
}

async function loadExistingTitles() {
  const context = { window: {}, console };
  context.window = context;
  vm.createContext(context);
  const filenames = [
    "questions.js",
    "outcomes.js",
    "media.js",
    "title-questions.js",
    "expanded-catalog.js",
  ];
  for (let generation = 2; generation < GENERATION; generation += 1) {
    filenames.push(`expanded-catalog-${generation}.js`);
  }
  for (const filename of filenames) {
    const source = await fs.readFile(path.join(DATA_DIRECTORY, filename), "utf8");
    vm.runInContext(source, context, { filename });
  }
  return new Set(Object.values(context.MEDIA).map((media) => normalizeTitle(media.officialTitle)));
}

async function fetchCandidates({ type, instance }) {
  const query = `
    SELECT DISTINCT ?item ?itemLabel ?sitelinks WHERE {
      ?item wdt:P31 wd:${instance}; wikibase:sitelinks ?sitelinks.
      FILTER(?sitelinks > 10)
      SERVICE wikibase:label { bd:serviceParam wikibase:language "en". }
    }
    ORDER BY DESC(?sitelinks)
    LIMIT 1400
  `;
  const url = new URL("https://query.wikidata.org/sparql");
  url.searchParams.set("query", query);
  url.searchParams.set("format", "json");
  const response = await fetch(url, {
    headers: { Accept: "application/sparql-results+json", "User-Agent": USER_AGENT },
  });
  if (!response.ok) throw new Error(`Wikidata ${type} query failed: ${response.status}`);
  const payload = await response.json();
  return payload.results.bindings.map((binding) => ({
    qid: binding.item.value.split("/").pop(),
    title: binding.itemLabel.value.trim(),
    type,
    sitelinks: Number(binding.sitelinks.value),
  }));
}

const existingTitles = await loadExistingTitles();
const selected = [];
const selectedTitles = new Set();

for (const target of TARGETS) {
  const candidates = await fetchCandidates(target);
  let added = 0;
  for (const candidate of candidates) {
    const normalized = normalizeTitle(candidate.title);
    if (
      !normalized ||
      candidate.title.length > 80 ||
      /^Q\d+$/.test(candidate.title) ||
      existingTitles.has(normalized) ||
      selectedTitles.has(normalized) ||
      ALTERNATE_TITLE_BLOCKLIST.has(normalized)
    ) continue;
    selected.push(candidate);
    selectedTitles.add(normalized);
    added += 1;
    if (added === target.count) break;
  }
  if (added < target.count) {
    throw new Error(`Only ${added} usable ${target.type} candidates; need ${target.count}.`);
  }
}

if (selected.length !== 500 || selectedTitles.size !== 500) {
  throw new Error(`Expansion ${GENERATION} contains ${selectedTitles.size} unique titles; expected 500.`);
}

