import fs from "node:fs/promises";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const DATA_DIR = path.join(ROOT, "charactercheck", "data");
const OUTPUT = path.join(DATA_DIR, "character-enrichment.js");
const CACHE = "/tmp/dexter-charactercheck-artwork-cache.json";
const ROLE_ORDER = ["heart", "mind", "spark", "wildcard"];

async function loadCatalog() {
  const context = { window: {}, console };
  context.window = context;
  vm.createContext(context);
  const filenames = ["questions.js", "outcomes.js", "media.js", "title-questions.js"];
  for (let generation = 1; generation <= 20; generation += 1) {
    const filename = generation === 1 ? "expanded-catalog.js" : `expanded-catalog-${generation}.js`;
    try {
      await fs.access(path.join(DATA_DIR, filename));
      filenames.push(filename);
    } catch {
      break;
    }
  }
  filenames.push("expanded-enrichment.js");
  for (const filename of filenames) {
    vm.runInContext(await fs.readFile(path.join(DATA_DIR, filename), "utf8"), context, { filename });
  }
  return context;
}

function needsNamedOutcomes(outcomes) {
  return ROLE_ORDER.some((role) => {
    const outcome = outcomes?.[role];
    const credit = String(outcome?.actor || outcome?.credit || "").trim();
    return !String(outcome?.character || "").trim() || !credit || /archetype/i.test(credit);
  });
}

function commonsImage(filename) {
  if (!filename) return "";
  return `https://commons.wikimedia.org/wiki/Special:Redirect/file/${encodeURIComponent(filename.replace(/ /g, "_"))}?width=1200`;
}

function commonsSource(filename) {
  if (!filename) return "";
  return `https://commons.wikimedia.org/wiki/File:${encodeURIComponent(filename.replace(/ /g, "_"))}`;
}

const context = await loadCatalog();
const cache = JSON.parse(await fs.readFile(CACHE, "utf8"));
const enrichment = {};
let realMatches = 0;
let fallbackMatches = 0;
let quizzesWithFourRealMatches = 0;

for (const [id, media] of Object.entries(context.MEDIA)) {
  const outcomes = context.OUTCOMES[id];
  if (!needsNamedOutcomes(outcomes)) continue;

  const entity = cache.entities?.[media.wikidataId];
  const seen = new Set();
  const candidates = [];
  for (const relatedId of entity?.related || []) {
    const person = cache.people?.[relatedId];
    const name = String(person?.label || "").trim();
    const normalized = name.toLocaleLowerCase("en");
    if (!name || /^Q\d+$/.test(name) || seen.has(normalized)) continue;
    seen.add(normalized);
    candidates.push({
      name,
      credit: `Featured character, cast member, creator, or subject connected to ${media.officialTitle}`,
      image: commonsImage(person?.image),
      sourceUrl: person?.image ? commonsSource(person.image) : `https://www.wikidata.org/wiki/${relatedId}`,
      real: true,
    });
    if (candidates.length === ROLE_ORDER.length) break;
  }

  if (candidates.length === ROLE_ORDER.length) quizzesWithFourRealMatches += 1;
  const fallbackNames = [
    `The ${media.officialTitle} Loyal Heart`,
    `The ${media.officialTitle} Mastermind`,
    `The ${media.officialTitle} Scene-Stealer`,
    `The ${media.officialTitle} Wild Card`,
  ];
  while (candidates.length < ROLE_ORDER.length) {
    const index = candidates.length;
    candidates.push({
      name: fallbackNames[index],
      credit: `A title-specific ${media.officialTitle} personality match`,
      image: "",
      sourceUrl: media.sourceUrl || "",
      real: false,
    });
  }

  enrichment[id] = ROLE_ORDER.map((role, index) => {
    const candidate = candidates[index];
    if (candidate.real) realMatches += 1;
    else fallbackMatches += 1;
    return [candidate.name, candidate.credit, candidate.image, candidate.sourceUrl];
  });
}

const source = `// Generated by scripts/build-charactercheck-character-enrichment.mjs.\n` +
`(() => {\n  "use strict";\n` +
`  const ROLES = ${JSON.stringify(ROLE_ORDER)};\n` +
`  const ENRICHMENT = ${JSON.stringify(enrichment)};\n` +
`  for (const [id, matches] of Object.entries(ENRICHMENT)) {\n` +
`    const outcomes = window.OUTCOMES?.[id];\n    if (!outcomes) continue;\n` +
`    ROLES.forEach((role, index) => {\n` +
`      const [character, actor, image, sourceUrl] = matches[index];\n` +
`      outcomes[role].character = character;\n      outcomes[role].actor = actor;\n` +
`      if (image) outcomes[role].image = image;\n      if (sourceUrl) outcomes[role].sourceUrl = sourceUrl;\n` +
`    });\n  }\n` +
`  window.CHARACTER_CHECK_CHARACTER_ENRICHMENT = Object.freeze({ quizzes: Object.keys(ENRICHMENT).length, realMatches: ${realMatches}, fallbackMatches: ${fallbackMatches}, quizzesWithFourRealMatches: ${quizzesWithFourRealMatches} });\n` +
`})();\n`;

await fs.writeFile(OUTPUT, source);
console.log(`Wrote ${path.relative(ROOT, OUTPUT)} for ${Object.keys(enrichment).length} quizzes.`);
console.log(`${realMatches} sourced matches; ${fallbackMatches} title-specific fallback matches; ${quizzesWithFourRealMatches} quizzes have four sourced matches.`);
